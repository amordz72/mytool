create or replace function public.admin_flexy_record_payment(
  p_account_uuid uuid,
  p_amount numeric,
  p_note text default null,
  p_request_key text default null
)
returns table(
  event_id bigint,
  debt_paid numeric,
  credit_added numeric,
  reused boolean
)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_account public.flexy_accounts%rowtype;
  v_debt numeric(18,2);
  v_debt_paid numeric(18,2);
  v_credit_added numeric(18,2);
  v_existing public.flexy_account_events%rowtype;
  v_result record;
  v_request text := nullif(btrim(coalesce(p_request_key,'')),'');
begin
  if not private.is_shop_admin() then raise exception 'PERMISSION_DENIED' using errcode='42501'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'INVALID_AMOUNT' using errcode='22023'; end if;

  select * into v_account
  from public.flexy_accounts a
  where a.account_uuid=p_account_uuid
    and a.status <> 'archived'
  for update;

  if not found then raise exception 'FLEXY_ACCOUNT_NOT_FOUND' using errcode='P0002'; end if;

  if v_request is not null then
    select * into v_existing
    from public.flexy_account_events e
    where e.account_id=v_account.id and e.request_key=v_request
    limit 1;
    if found then
      return query
      select
        v_existing.id,
        abs(least(v_existing.debt_delta,0)),
        greatest(v_existing.credit_delta,0),
        true;
      return;
    end if;
  end if;

  select coalesce(b.debt_balance,0) into v_debt
  from public.flexy_account_balances b
  where b.account_id=v_account.id;

  v_debt_paid := least(coalesce(v_debt,0),p_amount);
  v_credit_added := p_amount-v_debt_paid;

  select * into v_result
  from private.flexy_post_journal(
    v_account.id,
    'payment',
    p_amount,
    v_credit_added,
    -v_debt_paid,
    v_request,
    p_note,
    jsonb_build_object('debt_paid',v_debt_paid,'credit_added',v_credit_added),
    'دفع حساب Flexy'
  );

  return query select v_result.event_id,v_debt_paid,v_credit_added,v_result.reused;
end;
$function$;

