create or replace function public.admin_flexy_create_order_hold(
  p_account_uuid uuid,
  p_phone text,
  p_face_amount numeric,
  p_wallet_charge_amount numeric,
  p_request_key text,
  p_service_type text default 'offer',
  p_family text default null,
  p_network_index text default null
)
returns table(
  order_uuid uuid,
  status text,
  credit_reserved numeric,
  debt_reserved numeric,
  reused boolean
)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_account public.flexy_accounts%rowtype;
  v_balance record;
  v_existing public.flexy_orders%rowtype;
  v_phone text := regexp_replace(coalesce(p_phone,''),'[^0-9]','','g');
  v_request text := btrim(coalesce(p_request_key,''));
  v_charge numeric(18,2);
  v_credit numeric(18,2);
  v_debt numeric(18,2);
  v_order_id bigint;
  v_order_uuid uuid;
begin
  if not private.is_shop_admin() then raise exception 'PERMISSION_DENIED' using errcode='42501'; end if;
  if v_phone !~ '^0[5-7][0-9]{8}$' then raise exception 'INVALID_PHONE' using errcode='22023'; end if;
  if p_face_amount is null or p_face_amount <= 0 then raise exception 'INVALID_FACE_AMOUNT' using errcode='22023'; end if;
  if p_wallet_charge_amount is null or p_wallet_charge_amount <= 0 then raise exception 'INVALID_CHARGE_AMOUNT' using errcode='22023'; end if;
  if v_request='' then raise exception 'REQUEST_KEY_REQUIRED' using errcode='22023'; end if;

  select * into v_account
  from public.flexy_accounts a
  where a.account_uuid=p_account_uuid
  for update;

  if not found then raise exception 'FLEXY_ACCOUNT_NOT_FOUND' using errcode='P0002'; end if;
  if v_account.status <> 'active' then raise exception 'FLEXY_ACCOUNT_NOT_ACTIVE' using errcode='42501'; end if;

  select * into v_existing
  from public.flexy_orders o
  where o.account_id=v_account.id and o.request_key=v_request
  limit 1;

  if found then
    return query
    select
      v_existing.order_uuid,
      v_existing.status,
      coalesce((select h.credit_amount from public.flexy_wallet_holds h where h.order_id=v_existing.id),0),
      coalesce((select h.debt_amount from public.flexy_wallet_holds h where h.order_id=v_existing.id),0),
      true;
    return;
  end if;

  select * into v_balance
  from public.flexy_account_balances b
  where b.account_id=v_account.id;

  v_charge := p_wallet_charge_amount;
  v_credit := least(coalesce(v_balance.available_credit,0),v_charge);
  v_debt := v_charge-v_credit;

  if v_debt > 0 and not v_account.allow_debt then
    raise exception 'INSUFFICIENT_FLEXY_CREDIT' using errcode='P0001';
  end if;

  insert into public.flexy_orders(
    account_id,request_key,phone,operator,service_type,family,network_index,
    face_amount,wallet_charge_amount,rate_percent_applied,
    funding_mode,status,created_by_admin_user_id,reserved_at
  )
  values(
    v_account.id,v_request,v_phone,'mobilis',coalesce(nullif(btrim(p_service_type),''),'offer'),
    nullif(btrim(coalesce(p_family,'')),''),nullif(btrim(coalesce(p_network_index,'')),''),
    p_face_amount,v_charge,v_account.account_rate_percent,
    case
      when v_credit>0 and v_debt>0 then 'mixed'
      when v_credit>0 then 'credit'
      else 'debt'
    end,
    'reserved',auth.uid(),now()
  )
  returning id,flexy_orders.order_uuid into v_order_id,v_order_uuid;

  insert into public.flexy_wallet_holds(
    order_id,account_id,credit_amount,debt_amount,status
  )
  values(v_order_id,v_account.id,v_credit,v_debt,'active');

  return query select v_order_uuid,'reserved'::text,v_credit,v_debt,false;
end;
$function$;

create or replace function public.admin_flexy_list_accounts(
  p_search text default null,
  p_status text default null,
  p_limit integer default 25,
  p_offset integer default 0
)
returns table(
  account_uuid uuid,
  account_id bigint,
  display_name text,
  username text,
  status text,
  account_rate_percent numeric,
  allow_debt boolean,
  credit_balance numeric,
  debt_balance numeric,
  reserved_credit numeric,
  reserved_debt numeric,
  available_credit numeric,
  total_count bigint,
  updated_at timestamptz
)
language sql
security definer
set search_path=''
as $function$
  select
    b.account_uuid,b.account_id,b.display_name,b.username,b.status,
    b.account_rate_percent,b.allow_debt,b.credit_balance,b.debt_balance,
    b.reserved_credit,b.reserved_debt,b.available_credit,
    count(*) over() as total_count,b.updated_at
  from public.flexy_account_balances b
  where private.is_shop_admin()
    and (
      nullif(btrim(coalesce(p_search,'')),'') is null
      or b.display_name ilike '%'||btrim(p_search)||'%'
      or coalesce(b.username,'') ilike '%'||btrim(p_search)||'%'
      or b.account_id::text=btrim(p_search)
    )
    and (
      nullif(btrim(coalesce(p_status,'')),'') is null
      or b.status=btrim(p_status)
    )
  order by
    case when b.status='active' then 0 when b.status='blocked' then 1 else 2 end,
    b.updated_at desc,
    b.account_id desc
  limit greatest(1,least(coalesce(p_limit,25),100))
  offset greatest(coalesce(p_offset,0),0);
