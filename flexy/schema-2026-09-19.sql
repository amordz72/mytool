create index if not exists flexy_wallet_holds_account_status_idx
  on public.flexy_wallet_holds(account_id,status,created_at);

create table if not exists public.flexy_account_events (
  id bigint generated by default as identity primary key,
  event_uuid uuid not null default gen_random_uuid() unique,
  account_id bigint not null
    references public.flexy_accounts(id) on delete restrict,
  order_id bigint
    references public.flexy_orders(id) on delete set null,
  event_type text not null
    check (event_type in (
      'credit','debt','payment','refund',
      'order_capture','order_release','adjustment','reversal'
