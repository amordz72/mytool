create or replace view public.flexy_account_balances
with (security_invoker = true)
as
select
  fa.id as account_id,
  fa.account_uuid,
  fa.display_name,
  fa.username,
  fa.status,
  fa.account_rate_percent,
  fa.allow_debt,
  fa.currency_code,
  fa.credit_ledger_account_id,
  fa.debt_ledger_account_id,
  coalesce(cb.credit_total - cb.debit_total,0)::numeric(18,2) as credit_balance,
  coalesce(db.debit_total - db.credit_total,0)::numeric(18,2) as debt_balance,
  coalesce(h.reserved_credit,0)::numeric(18,2) as reserved_credit,
  coalesce(h.reserved_debt,0)::numeric(18,2) as reserved_debt,
  greatest(
    coalesce(cb.credit_total - cb.debit_total,0) - coalesce(h.reserved_credit,0),
    0
  )::numeric(18,2) as available_credit,
  (
    coalesce(cb.credit_total - cb.debit_total,0)
    - coalesce(db.debit_total - db.credit_total,0)
  )::numeric(18,2) as net_position,
  fa.created_at,
  fa.updated_at
from public.flexy_accounts fa
left join public.account_balances cb on cb.account_id=fa.credit_ledger_account_id
left join public.account_balances db on db.account_id=fa.debt_ledger_account_id
left join (
  select
    h.account_id,
    sum(case when h.status in ('active','review') then h.credit_amount else 0 end) as reserved_credit,
    sum(case when h.status in ('active','review') then h.debt_amount else 0 end) as reserved_debt
  from public.flexy_wallet_holds h
  group by h.account_id
) h on h.account_id=fa.id;

revoke all on public.flexy_account_balances from anon;
grant select on public.flexy_account_balances to authenticated;

