create table if not exists public.flexy_accounts (
  id bigint generated by default as identity primary key,
  account_uuid uuid not null default gen_random_uuid() unique,
  display_name text not null,
  username text,
  status text not null default 'active'
    check (status in ('active','blocked','archived')),
  account_rate_percent numeric(9,4) not null default 0
    check (account_rate_percent >= 0),
  allow_debt boolean not null default false,
  currency_code text not null default 'DZD'
    check (currency_code ~ '^[A-Z]{3}$'),
  credit_ledger_account_id bigint not null unique
    references public.accounts(id) on delete restrict,
  debt_ledger_account_id bigint not null unique
    references public.accounts(id) on delete restrict,
  core_identity_type text,
  core_identity_ref text,
  notes text,
  created_by_admin_user_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (nullif(btrim(display_name),'') is not null)
);

create unique index if not exists flexy_accounts_username_unique
  on public.flexy_accounts(lower(username))
  where username is not null and btrim(username) <> '';

create unique index if not exists flexy_accounts_core_identity_unique
  on public.flexy_accounts(core_identity_type,core_identity_ref)
  where core_identity_type is not null and core_identity_ref is not null;

create index if not exists flexy_accounts_status_idx
  on public.flexy_accounts(status,id desc);

create table if not exists public.flexy_orders (
  id bigint generated by default as identity primary key,
  order_uuid uuid not null default gen_random_uuid() unique,
  account_id bigint not null
    references public.flexy_accounts(id) on delete restrict,
  request_key text not null,
  phone text not null,
  operator text not null default 'mobilis',
  service_type text not null default 'offer',
  family text,
  network_index text,
  face_amount numeric(18,2) not null check (face_amount > 0),
  purchase_price numeric(18,2),
  sale_price numeric(18,2),
  wallet_charge_amount numeric(18,2) not null check (wallet_charge_amount > 0),
  profit_amount numeric(18,2),
  rate_percent_applied numeric(9,4) not null default 0,
  funding_mode text
    check (funding_mode is null or funding_mode in ('credit','debt','mixed')),
  status text not null default 'created'
    check (status in (
      'created','reserved','queued','claimed','execution_started',
      'success','failed','review','cancelled'
    )),
  station_job_uuid uuid unique
    references public.station_connect_jobs(job_uuid) on delete set null,
  result_code text,
  result_text text,
  created_by_admin_user_id uuid,
  created_at timestamptz not null default now(),
  reserved_at timestamptz,
  queued_at timestamptz,
  execution_started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique(account_id,request_key),
  check (phone ~ '^0[5-7][0-9]{8}$')
);

create index if not exists flexy_orders_queue_idx
