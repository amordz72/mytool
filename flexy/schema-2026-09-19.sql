create or replace function private.flexy_post_journal(
  p_account_id bigint,
  p_event_type text,
  p_amount numeric,
  p_credit_delta numeric,
  p_debt_delta numeric,
  p_request_key text,
  p_note text,
  p_metadata jsonb,
  p_description text
)
returns table(event_id bigint,journal_entry_id bigint,reused boolean)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_account public.flexy_accounts%rowtype;
  v_existing public.flexy_account_events%rowtype;
  v_control bigint;
  v_entry bigint;
  v_event bigint;
  v_debit_total numeric(18,2) := 0;
  v_credit_total numeric(18,2) := 0;
  v_credit_change numeric(18,2) := coalesce(p_credit_delta,0);
  v_debt_change numeric(18,2) := coalesce(p_debt_delta,0);
  v_control_net numeric(18,2);
  v_request text := nullif(btrim(coalesce(p_request_key,'')),'');
begin
  if not private.is_shop_admin() then
    raise exception 'PERMISSION_DENIED' using errcode='42501';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'INVALID_AMOUNT' using errcode='22023';
  end if;

  if p_event_type not in ('credit','debt','payment','refund','adjustment','reversal') then
    raise exception 'INVALID_EVENT_TYPE' using errcode='22023';
  end if;

  select * into v_account
  from public.flexy_accounts a
  where a.id=p_account_id
    and a.status <> 'archived'
  for update;

  if not found then
    raise exception 'FLEXY_ACCOUNT_NOT_FOUND' using errcode='P0002';
  end if;

  if v_request is not null then
    select * into v_existing
    from public.flexy_account_events e
    where e.account_id=p_account_id
      and e.request_key=v_request
    limit 1;

    if found then
      return query select v_existing.id,v_existing.journal_entry_id,true;
      return;
    end if;
  end if;

  v_control := private.flexy_control_account_id();
  if v_control is null then
    raise exception 'FLEXY_CONTROL_ACCOUNT_MISSING';
  end if;

  insert into public.journal_entries(
    description,status,source_type,branch_id,
    recorded_by_admin_user_id,notes
  )
  values (
    p_description,'draft','flexy_account',null,
    auth.uid(),nullif(btrim(coalesce(p_note,'')),'')
  )
  returning id into v_entry;

  -- Credit wallet balance is represented by a liability account:
  -- positive credit_delta => credit the liability, negative => debit it.
  if v_credit_change > 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_account.credit_ledger_account_id,0,v_credit_change,'رصيد Flexy');
    v_credit_total := v_credit_total + v_credit_change;
  elsif v_credit_change < 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_account.credit_ledger_account_id,abs(v_credit_change),0,'استهلاك/عكس رصيد Flexy');
    v_debit_total := v_debit_total + abs(v_credit_change);
  end if;

  -- Debt is represented by an asset account:
  -- positive debt_delta => debit receivable, negative => credit it.
  if v_debt_change > 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_account.debt_ledger_account_id,v_debt_change,0,'دين Flexy');
    v_debit_total := v_debit_total + v_debt_change;
  elsif v_debt_change < 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_account.debt_ledger_account_id,0,abs(v_debt_change),'تسديد/عكس دين Flexy');
    v_credit_total := v_credit_total + abs(v_debt_change);
  end if;

  v_control_net := v_debit_total - v_credit_total;

  if v_control_net > 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_control,0,v_control_net,'مقابل داخلي لمحفظة Flexy');
  elsif v_control_net < 0 then
    insert into public.journal_lines(journal_entry_id,account_id,debit,credit,memo)
    values(v_entry,v_control,abs(v_control_net),0,'مقابل داخلي لمحفظة Flexy');
  else
    -- A zero-net event would not produce a valid posted journal entry.
    raise exception 'ZERO_NET_FLEXY_EVENT' using errcode='22023';
  end if;

  update public.journal_entries
  set status='posted',posted_at=now()
  where id=v_entry;

  insert into public.flexy_account_events(
    account_id,event_type,amount,credit_delta,debt_delta,
    journal_entry_id,request_key,note,metadata,recorded_by_admin_user_id
  )
  values(
    p_account_id,p_event_type,p_amount,v_credit_change,v_debt_change,
    v_entry,v_request,nullif(btrim(coalesce(p_note,'')),''),
    coalesce(p_metadata,'{}'::jsonb),auth.uid()
  )
  returning id into v_event;

  update public.journal_entries
  set source_id=v_event
  where id=v_entry;

  return query select v_event,v_entry,false;
end;
$function$;

create or replace function public.admin_flexy_create_account(
  p_display_name text,
  p_username text default null,
  p_allow_debt boolean default false,
  p_account_rate_percent numeric default 0,
  p_notes text default null
)
returns table(
  account_uuid uuid,
  account_id bigint,
  display_name text
)
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_name text := btrim(coalesce(p_display_name,''));
  v_username text := nullif(btrim(coalesce(p_username,'')),'');
  v_credit bigint;
  v_debt bigint;
  v_id bigint;
  v_uuid uuid;
begin
  if not private.is_shop_admin() then
    raise exception 'PERMISSION_DENIED' using errcode='42501';
  end if;

  if v_name='' then
    raise exception 'INVALID_DISPLAY_NAME' using errcode='22023';
  end if;

  if coalesce(p_account_rate_percent,0) < 0 then
    raise exception 'INVALID_RATE' using errcode='22023';
  end if;

  insert into public.accounts(
    branch_id,name,account_type,account_subtype,currency_code,active,is_system,notes
  )
  values(
    null,'رصيد Flexy - '||v_name,'liability','flexy_customer_credit',
    'DZD',true,false,'حساب دفتر رصيد Flexy'
  )
  returning id into v_credit;

  insert into public.accounts(
    branch_id,name,account_type,account_subtype,currency_code,active,is_system,notes
  )
  values(
    null,'دين Flexy - '||v_name,'asset','flexy_customer_debt',
    'DZD',true,false,'حساب دفتر دين Flexy'
  )
  returning id into v_debt;

  insert into public.flexy_accounts(
    display_name,username,status,account_rate_percent,allow_debt,
    credit_ledger_account_id,debt_ledger_account_id,notes,
    created_by_admin_user_id
  )
  values(
    v_name,v_username,'active',coalesce(p_account_rate_percent,0),coalesce(p_allow_debt,false),
    v_credit,v_debt,nullif(btrim(coalesce(p_notes,'')),''),auth.uid()
  )
  returning id,flexy_accounts.account_uuid into v_id,v_uuid;

  return query select v_uuid,v_id,v_name;
end;
$function$;

create or replace function public.admin_flexy_update_account(
  p_account_uuid uuid,
  p_display_name text default null,
  p_username text default null,
  p_status text default null,
  p_allow_debt boolean default null,
  p_account_rate_percent numeric default null,
  p_notes text default null
)
returns boolean
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_account public.flexy_accounts%rowtype;
begin
  if not private.is_shop_admin() then
    raise exception 'PERMISSION_DENIED' using errcode='42501';
  end if;

  select * into v_account
  from public.flexy_accounts a
  where a.account_uuid=p_account_uuid
  for update;

  if not found then raise exception 'FLEXY_ACCOUNT_NOT_FOUND' using errcode='P0002'; end if;

  if p_status is not null and p_status not in ('active','blocked','archived') then
    raise exception 'INVALID_STATUS' using errcode='22023';
  end if;
  if p_account_rate_percent is not null and p_account_rate_percent < 0 then
    raise exception 'INVALID_RATE' using errcode='22023';
  end if;

  update public.flexy_accounts
  set display_name=case
        when p_display_name is null then display_name
        when nullif(btrim(p_display_name),'') is null then display_name
        else btrim(p_display_name)
      end,
      username=case
        when p_username is null then username
        else nullif(btrim(p_username),'')
      end,
      status=coalesce(p_status,status),
      allow_debt=coalesce(p_allow_debt,allow_debt),
      account_rate_percent=coalesce(p_account_rate_percent,account_rate_percent),
      notes=case when p_notes is null then notes else nullif(btrim(p_notes),'') end,
      updated_at=now()
  where account_uuid=p_account_uuid;

  return true;
end;
$function$;

